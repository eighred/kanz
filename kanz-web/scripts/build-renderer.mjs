// One compilation recipe for the production asset and independent qualification.
// No tool installation, alternate compiler, downloaded module or stale fallback.
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { createHash, randomUUID } from 'node:crypto'
import { lstatSync, readFileSync, mkdirSync, openSync, writeFileSync, fsyncSync, closeSync, renameSync, unlinkSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { homedir } from 'node:os'

export const root = fileURLToPath(new URL('../../', import.meta.url))
export const inputs = ['kanz-rs/Cargo.toml', 'kanz-rs/Cargo.lock', 'kanz-rs/rust-toolchain.toml',
  'kanz-rs/crates/browser-render/Cargo.toml', 'kanz-rs/crates/browser-render/src/lib.rs',
  'kanz-web/scripts/build-renderer.mjs', 'kanz-web/scripts/build-renderer.test.mjs', 'kanz-web/.nvmrc']
export const exportsExpected = ['memory:memory', 'global:__data_end', 'global:__heap_base',
  'function:render_input_byte', 'function:render_output_byte', 'function:render_output_len',
  'function:render_reset', 'function:render_value'].sort()
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
const command = (name, args, cwd = root) => execFileSync(name, args,
  { cwd, timeout: 120000, maxBuffer: 4 * 1024 * 1024 })
const git = (...args) => command('git', args).toString('utf8').trim()

export function validateModule(bytes) {
  assert(bytes.length > 0 && bytes.length <= 2 * 1024 * 1024)
  const module = new WebAssembly.Module(bytes)
  assert.deepEqual(WebAssembly.Module.imports(module), [])
  assert.deepEqual(WebAssembly.Module.exports(module).map(x => `${x.kind}:${x.name}`).sort(), exportsExpected)
  const instance = new WebAssembly.Instance(module)
  for (const [name, arity] of Object.entries({ render_reset: 0, render_input_byte: 2,
    render_value: 2, render_output_len: 0, render_output_byte: 1 })) {
    assert.equal(instance.exports[name].length, arity)
  }
  const memory = instance.exports.memory
  assert(memory instanceof WebAssembly.Memory)
  const pages = memory.buffer.byteLength / 65536
  assert(Number.isInteger(pages) && pages > 0 && pages <= 32)
  assert.equal(memory.grow(32 - pages), pages)
  assert.throws(() => memory.grow(1), RangeError)
  // Discard this validation instance: runtime receives its own initial memory.
  return hash(bytes)
}

function statOrMissing(path) {
  try { return lstatSync(path) } catch (error) { if (error.code === 'ENOENT') return null; throw error }
}

export function checkCompilerConfiguration(start, cargoHome, environment) {
  for (let directory = start; ; directory = dirname(directory)) {
    for (const name of ['config', 'config.toml']) assert.equal(statOrMissing(resolve(directory, '.cargo', name)), null)
    if (dirname(directory) === directory) break
  }
  for (const name of ['config', 'config.toml']) assert.equal(statOrMissing(resolve(cargoHome, name)), null)
  for (const name of Object.keys(environment)) {
    if (/^CARGO_PROFILE_/.test(name) || /^(RUSTC_BOOTSTRAP|RUSTFLAGS|CARGO_ENCODED_RUSTFLAGS|RUSTC|RUSTC_WRAPPER|RUSTC_WORKSPACE_WRAPPER|CARGO_BUILD_RUSTFLAGS|CARGO_BUILD_RUSTC|CARGO_BUILD_RUSTC_WRAPPER|CARGO_BUILD_RUSTC_WORKSPACE_WRAPPER|CARGO_TARGET_.*_(RUSTFLAGS|LINKER|RUNNER))$/.test(name)) {
      assert(!environment[name], 'ambient compiler configuration is unsupported')
    }
  }
}

export function publishAsset(directory, bytes, descriptor) {
  const moduleSHA256 = validateModule(bytes)
  assert.equal(descriptor.moduleSHA256, moduleSHA256)
  for (let parent = dirname(directory); ; parent = dirname(parent)) {
    const stat = lstatSync(parent)
    assert(stat.isDirectory() && !stat.isSymbolicLink())
    if (dirname(parent) === parent) break
  }
  try { mkdirSync(directory) } catch (error) { if (error.code !== 'EEXIST') throw error }
  const stat = lstatSync(directory)
  assert(stat.isDirectory() && !stat.isSymbolicLink())
  const name = `browser-render.${moduleSHA256}.wasm`, path = resolve(directory, name)
  let fd
  try {
    fd = openSync(path, 'wx', 0o600)
    writeFileSync(fd, bytes); fsyncSync(fd)
  } catch (error) {
    if (error.code !== 'EEXIST') throw error
    const existing = lstatSync(path)
    assert(existing.isFile() && !existing.isSymbolicLink() && existing.nlink === 1 && existing.size === bytes.length)
    assert.deepEqual(readFileSync(path), bytes)
  } finally { if (fd !== undefined) closeSync(fd) }
  const entry = resolve(directory, 'browser-render.ts'), previous = statOrMissing(entry)
  assert(previous === null || (previous.isFile() && !previous.isSymbolicLink() && previous.nlink === 1))
  const temporary = resolve(directory, `.browser-render-${randomUUID()}.tmp`)
  const data = `// Generated by the shared pinned recipe.\nimport url from './${name}?url&no-inline'\nexport const rendererAsset = ${JSON.stringify(descriptor)} as const\nexport { url }\n`
  let owned = false
  try {
    const handle = openSync(temporary, 'wx', 0o600); owned = true
    try { writeFileSync(handle, data); fsyncSync(handle) } finally { closeSync(handle) }
    renameSync(temporary, entry); owned = false
  } finally { if (owned) unlinkSync(temporary) }
  // The sole atomic entrypoint commits the descriptor and immutable module
  // together. Never prune unrelated files or prior content-addressed assets.
}

export function build() {
  checkCompilerConfiguration(resolve(root, 'kanz-rs'), process.env.CARGO_HOME || resolve(homedir(), '.cargo'), process.env)
  const source = git('rev-parse', 'HEAD'), tree = git('rev-parse', 'HEAD^{tree}')
  assert.match(source, /^[0-9a-f]{40}$/)
  assert.match(tree, /^[0-9a-f]{40}$/)
  const sources = Object.fromEntries(inputs.map(name => {
    const path = resolve(root, name), stat = lstatSync(path)
    assert(stat.isFile() && !stat.isSymbolicLink() && stat.size <= 4 * 1024 * 1024)
    const bytes = readFileSync(path)
    if (process.env.GITHUB_ACTIONS === 'true') {
      assert.equal(git('ls-files', '--error-unmatch', '--', name), name)
      assert.deepEqual(bytes, command('git', ['show', `HEAD:${name}`]))
    }
    return [name, hash(bytes)]
  }))
  if (process.env.GITHUB_ACTIONS === 'true') {
    assert.equal(source, process.env.GITHUB_SHA)
    assert.match(process.env.GITHUB_RUN_ID || '', /^[1-9][0-9]{0,19}$/)
    assert.match(process.env.GITHUB_RUN_ATTEMPT || '', /^[1-9][0-9]{0,19}$/)
    assert.equal(process.versions.node.split('.')[0], readFileSync(resolve(root, 'kanz-web/.nvmrc'), 'utf8').trim())
  }
  command(process.execPath, ['--test', resolve(root, 'kanz-web/scripts/build-renderer.test.mjs')])
  assert.match(command('rustc', ['+1.90.0', '--version']).toString(), /^rustc 1\.90\.0 /)
  command('cargo', ['+1.90.0', 'rustc', '--locked', '--release', '-p', 'kanz-browser-render',
    '--target', 'wasm32-unknown-unknown', '--target-dir', resolve(root, 'kanz-rs/target'), '--', '-C', 'link-arg=--max-memory=2097152',
    '-C', 'link-arg=-zstack-size=65536'], resolve(root, 'kanz-rs'))
  const output = resolve(root, 'kanz-rs/target/wasm32-unknown-unknown/release/kanz_browser_render.wasm')
  const stat = lstatSync(output)
  assert(stat.isFile() && !stat.isSymbolicLink() && stat.size <= 2 * 1024 * 1024)
  const bytes = readFileSync(output), moduleSHA256 = validateModule(bytes)
  for (const [name, expected] of Object.entries(sources)) assert.equal(hash(readFileSync(resolve(root, name))), expected)
  checkCompilerConfiguration(resolve(root, 'kanz-rs'), process.env.CARGO_HOME || resolve(homedir(), '.cargo'), process.env)
  const descriptor = { format: 'kanz-browser-render-asset-v1', abi: 1, source, tree,
    sourceKind: process.env.GITHUB_ACTIONS === 'true' ? 'committed-ci' : 'local-build',
    run: process.env.GITHUB_ACTIONS === 'true' ? process.env.GITHUB_RUN_ID : null,
    attempt: process.env.GITHUB_ACTIONS === 'true' ? process.env.GITHUB_RUN_ATTEMPT : null,
    sources, moduleSHA256, moduleBytes: bytes.length, maxMemoryBytes: 2097152 }
  publishAsset(resolve(root, 'kanz-web/src/generated'), bytes, descriptor)
  return descriptor
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  assert.equal(process.argv.length, 2)
  let result
  try { result = build() } catch {
    console.error('Pinned browser renderer build failed; no stale asset fallback. Verify Rust 1.90.0, wasm32 target and source/configuration prerequisites.')
    process.exit(1)
  }
  console.log(JSON.stringify({ moduleSHA256: result.moduleSHA256, moduleBytes: result.moduleBytes,
    source: result.source, sourceKind: result.sourceKind }))
}
