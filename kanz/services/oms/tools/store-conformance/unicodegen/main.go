// Command unicodegen exports the pinned Go normalization data used by the Rust port.
package main

import (
	"bufio"
	"fmt"
	"os"
	"unicode"
	"unicode/utf8"
)

func main() {
	w := bufio.NewWriter(os.Stdout)
	fmt.Fprintln(w, "// Code generated by the pinned Go unicodegen tool; DO NOT EDIT.")
	fmt.Fprintf(w, "// Go Unicode data version %s; simple lowercase and White_Space semantics.\n", unicode.Version)
	fmt.Fprintln(w, "#[rustfmt::skip]")
	fmt.Fprintln(w, "pub(crate) const LOWER: &[(u32, u32)] = &[")
	for r := rune(0); r <= utf8.MaxRune; r++ {
		if r >= 0xd800 && r <= 0xdfff {
			continue
		}
		if l := unicode.ToLower(r); l != r {
			fmt.Fprintf(w, "    (0x%x, 0x%x),\n", r, l)
		}
	}
	fmt.Fprintln(w, "];")
	fmt.Fprintln(w, "#[rustfmt::skip]")
	fmt.Fprintln(w, "pub(crate) const SPACE: &[u32] = &[")
	for r := rune(0); r <= utf8.MaxRune; r++ {
		if unicode.IsSpace(r) {
			fmt.Fprintf(w, "    0x%x,\n", r)
		}
	}
	fmt.Fprintln(w, "];")
	if e := w.Flush(); e != nil {
		fmt.Fprintln(os.Stderr, "Unicode export failed")
		os.Exit(1)
	}
}
